def run_import():
    sql = """
    ALTER TABLE exercises
    ADD COLUMN IF NOT EXISTS sub_group VARCHAR(50),
    ADD COLUMN IF NOT EXISTS image_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS image_secondary_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS video_url VARCHAR(500);
    ALTER TABLE exercises ALTER COLUMN equipment TYPE VARCHAR(100);
    """
    with engine.begin() as conn:
        conn.execute(text(sql))

    db = SessionLocal()
    try:
        existing = {row.name.lower() for row in db.query(Exercise.name).all()}
        added = 0
        for name, mg, sg, eq, tech, sb, sk, se in CATALOG:
            if name.lower() not in existing:
                db.add(Exercise(
                    name=name,
                    muscle_group=mg,
                    sub_group=sg,
                    equipment=eq,
                    technique_tips=tech,
                    common_mistakes="Избегайте рывков, инерции и перегруза суставов.",
                    safe_for_lower_back=sb,
                    safe_for_knees=sk,
                    safe_for_elbows=se
                ))
                added += 1
        db.commit()
        print(f"ГОТОВО! Добавлено {added} упражнений. Всего в базе: {db.query(Exercise).count()}!")
    finally:
        db.close()


if __name__ == "__main__":
    run_import()


